    [Fact]
    public void DecimalExtremes_RetainEveryMillionGroupAndSign()
    {
        const string maximum = "เจ็ดหมื่นเก้าพันสองร้อยยี่สิบแปดล้านหนึ่งแสนหกหมื่นสองพันห้าร้อยสิบสี่ล้านสองแสนหกหมื่นสี่พันสามร้อยสามสิบเจ็ดล้านห้าแสนเก้าหมื่นสามพันห้าร้อยสี่สิบสามล้านเก้าแสนห้าหมื่นสามร้อยสามสิบห้าบาทถ้วน";
